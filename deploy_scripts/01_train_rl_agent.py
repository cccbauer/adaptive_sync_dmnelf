# ============================================================================
# DEPLOYMENT FUNCTIONS
# ============================================================================

def compile_check():
    """Verify script compiles"""
    temp_file = Path("/tmp/01_train_rl_agent_cluster.py")
    with open(temp_file, 'w') as f:
        f.write('\n'.join(CLUSTER_SCRIPT))
    
    try:
        py_compile.compile(str(temp_file), doraise=True)
        print("✓ Cluster script compiles")
        temp_file.unlink()
        return True
    except py_compile.PyCompileError as e:
        print(f"✗ Compilation error: {e}")
        return False

def deploy_to_cluster():
    """Deploy scripts to cluster"""
    print("\n1. Creating cluster directories...")
    
    # Create directories
    dirs = [
        config.CLUSTER_BASE,
        config.CLUSTER_SCRIPTS,
        config.CLUSTER_LOGS,
        config.CLUSTER_MODELS,
        config.CLUSTER_RESULTS
    ]
    
    for d in dirs:
        cmd = f"mkdir -p {d}"
        subprocess.run(config.ssh_command(cmd), shell=True, check=True)
    
    print("   ✓ Directories created")
    
    # Copy Python script
    print("\n2. Copying cluster script...")
    local_cluster_script = config.LOCAL_SCRIPTS / "01_train_rl_agent_cluster.py"
    with open(local_cluster_script, 'w') as f:
        f.write('\n'.join(CLUSTER_SCRIPT))
    
    cmd = config.scp_to_cluster(
        local_cluster_script,
        config.CLUSTER_SCRIPTS / "01_train_rl_agent_cluster.py"
    )
    subprocess.run(cmd, shell=True, check=True)
    print("   ✓ Python script copied")
    
    # Copy SLURM script
    print("\n3. Copying SLURM script...")
    local_slurm_script = config.LOCAL_SCRIPTS / "01_train_rl_agent.sh"
    with open(local_slurm_script, 'w') as f:
        f.write('\n'.join(SLURM_SCRIPT))
    
    cmd = config.scp_to_cluster(
        local_slurm_script,
        config.CLUSTER_SCRIPTS / "01_train_rl_agent.sh"
    )
    subprocess.run(cmd, shell=True, check=True)
    print("   ✓ SLURM script copied")
    
    # Copy src modules
    print("\n4. Copying source modules...")
    src_modules = ['kuramoto.py', 'energy.py', 'agents.py']
    for module in src_modules:
        local_file = config.LOCAL_BASE / 'src' / 'models' / module
        cluster_file = config.CLUSTER_BASE / 'src' / 'models' / module
        
        # Create src/models on cluster
        cmd = f"mkdir -p {config.CLUSTER_BASE / 'src' / 'models'}"
        subprocess.run(config.ssh_command(cmd), shell=True, check=True)
        
        cmd = config.scp_to_cluster(local_file, cluster_file)
        subprocess.run(cmd, shell=True, check=True)
    
    print("   ✓ Source modules copied")

def submit_job():
    """Submit SLURM job"""
    print("\n5. Submitting SLURM job...")
    
    cmd = f"sbatch {config.CLUSTER_SCRIPTS / '01_train_rl_agent.sh'}"
    result = subprocess.run(
        config.ssh_command(cmd),
        shell=True,
        capture_output=True,
        text=True
    )
    
    if result.returncode == 0:
        job_id = result.stdout.strip().split()[-1]
        print(f"   ✓ Job submitted: {job_id}")
        return job_id
    else:
        print(f"   ✗ Submission failed: {result.stderr}")
        return None

# ============================================================================
# MAIN
# ============================================================================

if __name__ == "__main__":
    print("=" * 70)
    print("Deploy: Train RL Agent on Cluster")
    print("=" * 70)
    
    # Compile check
    if not compile_check():
        sys.exit(1)
    
    # Deploy
    try:
        deploy_to_cluster()
        job_id = submit_job()
        
        if job_id:
            print("\n" + "=" * 70)
            print("Deployment successful!")
            print("=" * 70)
            print(f"\nJob ID: {job_id}")
            print("\nMonitor job:")
            print(f"  ssh {config.CLUSTER_USER}@{config.CLUSTER_HOST} 'squeue -j {job_id}'")
            print("\nCheck log:")
            print(f"  ssh {config.CLUSTER_USER}@{config.CLUSTER_HOST} 'tail -f {config.CLUSTER_LOGS}/rl_train_{job_id}.out'")
    
    except Exception as e:
        print(f"\n✗ Deployment failed: {e}")
        sys.exit(1)
